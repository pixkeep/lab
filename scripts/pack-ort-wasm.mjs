#!/usr/bin/env node
// Packs the ONNX Runtime Web artifacts that /background-removal/ self-hosts.
// Re-run after bumping @huggingface/transformers (it pins the runtime):
//
//   node scripts/pack-ort-wasm.mjs
//
// Why the .wasm files are stored gzipped: Cloudflare caps a single static
// asset at 25 MiB, and the runtime binaries that can execute on WebGPU are
// larger than that in onnxruntime-web 1.31 (26.9 MB asyncify, 28.4 MB jsep).
// The worker inflates them with DecompressionStream and hands the bytes to the
// runtime (env.backends.onnx.wasm.wasmBinary). gzip rather than brotli because
// the Compression Streams API only defines gzip and deflate.
//
// The .mjs files are the runtime's own loader scripts, copied unmodified; the
// runtime imports them from this origin when a session is created.
//
// Outputs (all committed):
//   public/ort/*.{mjs,wasm.gz}          the artifacts
//   src/lib/ort-manifest.json           file names + sizes + hashes, read by the worker
//   public/ort/README.md                the same facts for humans

import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import zlib from 'node:zlib';

const ASSET_LIMIT_BYTES = 25 * 1024 * 1024; // Cloudflare Workers static assets, per file

// cpu = CPU (wasm) execution provider only, the smallest build.
// webgpu = the build ORT's own `onnxruntime-web/webgpu` bundle names as its
// default loader; it runs both the WebGPU and the CPU provider.
const FLAVORS = [
  { key: 'cpu', base: 'ort-wasm-simd-threaded' },
  { key: 'webgpu', base: 'ort-wasm-simd-threaded.asyncify' },
];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Resolve the runtime from transformers.js, not from the top level: that is the
// copy the library actually imports. Neither package exports its package.json,
// so start from the main entry and step up to the package directory.
const require = createRequire(import.meta.url);
const transformersDir = path.dirname(path.dirname(require.resolve('@huggingface/transformers')));
const ortDist = path.dirname(createRequire(path.join(transformersDir, 'package.json')).resolve('onnxruntime-web'));
const ortVersion = JSON.parse(fs.readFileSync(path.join(ortDist, '..', 'package.json'), 'utf8')).version;

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const outDir = path.join(root, 'public', 'ort');
fs.mkdirSync(outDir, { recursive: true });

const manifest = { ortVersion, packedOn: new Date().toISOString().slice(0, 10), flavors: {} };

for (const { key, base } of FLAVORS) {
  const mjs = fs.readFileSync(path.join(ortDist, `${base}.mjs`));
  const wasm = fs.readFileSync(path.join(ortDist, `${base}.wasm`));

  // Always gzipped, including the build that would fit uncompressed: the repo
  // is what grows otherwise, and Cloudflare would compress it on the wire
  // anyway.
  const wasmFile = `${base}.wasm.gz`;
  const packed = zlib.gzipSync(wasm, { level: 9 });

  // A corrupted artifact would only surface as an opaque runtime failure in
  // the browser — fail here instead.
  if (sha256(zlib.gunzipSync(packed)) !== sha256(wasm)) {
    throw new Error(`${base}.wasm: gzip round-trip mismatch`);
  }
  if (packed.length > ASSET_LIMIT_BYTES) {
    throw new Error(`${base}.wasm.gz is ${packed.length} bytes — still over the ${ASSET_LIMIT_BYTES}-byte asset limit`);
  }

  fs.writeFileSync(path.join(outDir, `${base}.mjs`), mjs);
  fs.writeFileSync(path.join(outDir, wasmFile), packed);

  manifest.flavors[key] = {
    mjs: `/ort/${base}.mjs`,
    wasm: `/ort/${wasmFile}`,
    compressed: 'gzip',
    rawBytes: wasm.length,
    shippedBytes: packed.length,
    mjsBytes: mjs.length,
    rawSha256: sha256(wasm),
    shippedSha256: sha256(packed),
  };

  console.log(
    `${key.padEnd(6)} ${base.padEnd(34)} raw ${String(wasm.length).padStart(9)}  shipped ${String(packed.length).padStart(9)}  gzip ${(100 * packed.length / wasm.length).toFixed(1)}%`,
  );
}

fs.writeFileSync(
  path.join(root, 'src', 'lib', 'ort-manifest.json'),
  `${JSON.stringify(manifest, null, 2)}\n`,
);

const mb = (n) => `${(n / 1048576).toFixed(2)} MB`;
const rows = Object.entries(manifest.flavors)
  .map(([key, f]) => {
    const file = f.wasm.split('/').pop();
    return `| \`${key}\` | \`${file}\` | ${mb(f.rawBytes)} | ${mb(f.shippedBytes)} | \`${f.shippedSha256}\` |`;
  })
  .join('\n');

fs.writeFileSync(
  path.join(outDir, 'README.md'),
  `# ONNX Runtime Web artifacts

Generated by \`scripts/pack-ort-wasm.mjs\` — do not edit. Regenerate after bumping
\`@huggingface/transformers\` (it pins the runtime).

- Runtime: \`onnxruntime-web@${manifest.ortVersion}\`, read from the copy that
  \`@huggingface/transformers\` imports.
- Packed on ${manifest.packedOn} with \`node scripts/pack-ort-wasm.mjs\`.
- The \`.wasm\` files are gzipped because Cloudflare caps a single static asset at
  25 MiB. \`/background-removal/\` inflates them in its worker and passes the bytes
  to the runtime; the \`.mjs\` files are the runtime's loader scripts, unmodified.

| Flavor | File | Uncompressed | Shipped | sha256 of shipped file |
|---|---|---|---|---|
${rows}

Uncompressed sha256 and file sizes are in \`src/lib/ort-manifest.json\`.
`,
);

console.log(`ort ${ortVersion} → public/ort/, src/lib/ort-manifest.json`);
